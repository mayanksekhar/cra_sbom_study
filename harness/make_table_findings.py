#!/usr/bin/env python3
import collections, csv
from pathlib import Path
root = Path(__file__).resolve().parent.parent
sets = [("pilot HEAD (10 projects)", "results/findings_vs_reference.csv"), ("older pins (6)", "results_old/findings_vs_reference.csv"),
        ("Go (10)", "results_go/findings_vs_reference.csv"), ("Maven (8)", "results_mvn/findings_vs_reference.csv"), ("PyPI (8)", "results_py/findings_vs_reference.csv"),
        ("Rust (8)", "results_rust/findings_vs_reference.csv"), ("npm (3)", "results_npm/findings_vs_reference.csv")]
K = ("ref_n", "tp", "fn", "fn_component_absent", "fn_no_version", "fn_wrong_version", "fn_scanner_miss")
lines = ["# Findings recovered against the reference (generated by harness/make_table_findings.py)", "",
         "Scanner: Grype. Unit: one finding per component and issue (alias cluster). Reference: findings Grype reports on an SBOM built from the shipped set truth.", "",
         "| Set | Generator | Reference findings | Found | Missed | Absent component | No version | Wrong version | Scanner miss |", "|---|---|---|---|---|---|---|---|---|"]
tot = collections.Counter()
for label, f in sets:
    agg = collections.defaultdict(collections.Counter)
    for r in csv.DictReader(open(root / f)):
        if r["scanner"] == "grype" and not r["project"].endswith("_nolock"):
            for k in K:
                agg[r["tool"]][k] += int(r[k])
    for t, a in sorted(agg.items()):
        lines.append(f"| {label} | {t} | {a['ref_n']} | {a['tp']} | {a['fn']} | {a['fn_component_absent']} | {a['fn_no_version']} | {a['fn_wrong_version']} | {a['fn_scanner_miss']} |")
        if t == "cdxgen":
            tot["ref"] += a["ref_n"]
lines += ["", f"Reference findings over the seven sets: {tot['ref']}."]
(root / "docs" / "table_findings.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines[-4:]))
